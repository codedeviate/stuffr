#!/bin/sh
# Usage: gen-prefix-header.sh <archive.a> <out.h>
#
# Writes `#define NAME stuffr_NAME` for every global symbol the archive
# defines (code and data; the leading `_` of Mach-O names is stripped), sorted.
# build.rs force-includes the header into every vendored translation unit, so
# the library's exports carry the `stuffr_` prefix and cannot clash with
# another copy of the library in a downstream binary.
#
# Regenerate whenever the vendored library changes (a new version adds or
# drops symbols): empty the library's `stuffr-prefix.h`, build once
# (`cargo build -p stuffr-formats --features <lib>-c`), run this on the
# `lib<lib>_vendored.a` in target/debug/build/stuffr-formats-*/out/, and
# commit the header. `cargo test -p stuffr-formats --features <lib>-c
# --test vendored_symbols` fails while any export is still unprefixed.
set -eu
[ "$#" -eq 2 ] || { echo "usage: $0 <archive.a> <out.h>" >&2; exit 2; }
archive=$1
out=$2
if [ "$(uname -s)" = Darwin ]; then
    list=$(nm -gU "$archive" | awk 'NF == 3 && $2 != "U" { n = $3; sub(/^_/, "", n); print n }')
else
    list=$(nm -g --defined-only "$archive" | awk 'NF == 3 && $2 != "U" { print $3 }')
fi
list=$(printf '%s\n' "$list" | LC_ALL=C sort -u)
{
    echo "/* Generated by scripts/gen-prefix-header.sh from the library's own archive;"
    echo " * do not edit. Every global symbol the vendored library defines is renamed"
    echo " * stuffr_NAME, so it cannot clash with another copy in a downstream binary. */"
    printf '%s\n' "$list" | while IFS= read -r name; do
        [ -n "$name" ] && echo "#define $name stuffr_$name"
    done
} > "$out"
